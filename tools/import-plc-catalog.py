"""Import the Mitsubishi practice PLC subset from qet-io-builder's model JSONs.

Usage: python tools/import-plc-catalog.py ../qet-io-builder
Voltage selection is checked against SH-082451Q, SH-080024AJ, SH-081246M
and SH-082633E. The practice board has 0V-common input devices.
"""
import json
import pathlib
import sys


def terminal_block(pins):
    return pins == 'TB16' or isinstance(pins, list) and all(p.startswith('TB') for p in pins)


def collect(root):
    cpus, racks, mixed = [], {}, []
    for p in sorted((root / 'iq_f/cpu').glob('*.json')):
        j = json.loads(p.read_text(encoding='utf-8'))
        d, model = j['definition'], j['model']
        outputs = sum(g[2] for g in d['outputs'])
        if d['inputs'] != 16 or not 14 <= outputs <= 16:
            continue
        # /ES: AC100-240V supply, relay or NPN sink; exclude DC supply and EC variants.
        if not model.endswith(('MR/ES', 'MT/ES')):
            continue
        cpus.append(dict(model=model, **{k: d[k] for k in
            ('series', 'inputs', 'outputs', 'in_common', 'service', 'source')},
            physical_io=d.get('physical_io'), output_type='relay' if 'MR/' in model else 'sink'))
    for family in ('q', 'iq_r'):
        ins, outs = [], []
        for p in sorted((root / family / 'digital_io').glob('*.json')):
            j = json.loads(p.read_text(encoding='utf-8')); d = j['definition']; model = j['model']
            if 'input' in d:
                if d['input']['points'] == 16 and 14 <= d['output']['points'] <= 16 and d['output']['out'] == 'sink' and terminal_block(d['input']['pins']) and terminal_block(d['output']['pins']):
                    mixed.append(dict(model=model, series=family, input=d['input'], output=d['output'], source=d['source']))
                continue
            if d.get('io') == 'in':
                # RX6/RX7 are 5/12V; negative-only commons cannot drive this board.
                if model.startswith(('RX6', 'RX7')) or d.get('input_common') == 'negative':
                    continue
                if d['points'] == 16 and terminal_block(d['pins']):
                    ins.append(dict(model=model, **{k: d[k] for k in ('points', 'pins', 'common')},
                        common_group_points=d.get('common_group_points'), source=d.get('source', 'SH-080024AJ')))
            elif d.get('out') in ('relay', 'sink') and 14 <= d['points'] <= 16 and terminal_block(d['pins']):
                outs.append(dict(model=model, **{k: d[k] for k in ('points', 'pins', 'out', 'com')},
                    vplus=d.get('vplus', ''), source=d.get('source', 'SH-080024AJ')))
        racks[family] = dict(inputs=ins, outputs=outs)
    assert cpus and all(r['inputs'] and r['outputs'] for r in racks.values())
    return dict(cpus=cpus, racks=racks, mixed=mixed)


if __name__ == '__main__':
    data = collect(pathlib.Path(sys.argv[1]) / 'parts/plc/mitsubishi')
    dest = pathlib.Path(__file__).resolve().parents[1] / 'src/SequenceDojo/wwwroot/js/plc-catalog-data.js'
    dest.write_text('// Generated by tools/import-plc-catalog.py; edit the source model JSONs to update.\n'
                    'export const PLC_CATALOG = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(f"Imported {len(data['cpus'])} CPUs, {len(data['mixed'])} mixed modules, "
          f"{sum(len(r['inputs']) + len(r['outputs']) for r in data['racks'].values())} I/O modules")
